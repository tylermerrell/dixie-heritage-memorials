            <h2>The Two Primary Engraving Techniques</h2>
            <p>Every custom design on a headstone is produced using one of two techniques — sandblasting or laser etching. The choice is not just aesthetic; the two age differently in Southern Utah's punishing climate.</p>

            <h3>Sandblasting</h3>
            <p>The traditional technique. A rubber stencil is cut to the design, applied to the granite, and sand-blasted under high pressure — carving the design into the granite as a recessed line drawing. The recessed carving is then filled with white or contrasting paint, which brings the design forward against the polished granite background.</p>
            <p>Best for: Traditional text, larger design elements (temple silhouettes, family emblems, scripture references), sandblast-friendly granites (Barre Gray, Impala Black). The carving itself is permanent; the paint fill requires refreshing every 30–50 years.</p>

            <h3>Laser Etching</h3>
            <p>The modern technique. A high-precision laser removes the polished surface of the granite in microscopic passes, turning the etched areas white against the surrounding polished dark background. Because the etching is a surface treatment (not a deep carving), it can reproduce photographic detail — portraits, complex line art, subtle tonal gradation.</p>
            <p>Best for: Portraits, photographic imagery, contemporary temple silhouettes (particularly Red Cliffs), fine detail work, and any design where you want the visual contrast without paint fill. Best on jet black or midnight black polished granite. Reads cleanly for 75–100+ years without maintenance.</p>
