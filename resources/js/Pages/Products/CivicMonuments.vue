            <h2>The Committee Process</h2>
            <p>Civic monument projects almost always involve a committee — a veterans group, a historical society board, a city council, or a ward heritage committee. The process is different from a family headstone in structure:</p>
            <ol>
              <li><strong>Initial concept meeting.</strong> The committee shares the intent, scope, budget range, and timeline. We share what is feasible at that budget and produce a written scope.</li>
              <li><strong>Design concept.</strong> Preliminary sketches or 3D renderings showing scale, layout, materials, and inscription concept.</li>
              <li><strong>Committee revision.</strong> Feedback from the group, incorporating stakeholders who couldn't attend the first meeting. Usually 2–3 revision rounds.</li>
              <li><strong>Formal approval.</strong> Signed proof and contract from the committee's authorized signatory.</li>
              <li><strong>Manufacturing.</strong> Larger monuments involve longer lead times — 4–8 months from proof approval is typical for a substantial civic installation.</li>
              <li><strong>Site preparation.</strong> Foundation, drainage, adjacent landscaping, lighting hookups, and utility coordination all handled before delivery.</li>
              <li><strong>Delivery and installation.</strong> Large-crew install with crane where needed. Coordination with the client's dedication timeline.</li>
