            <h2>Hard Water and Flat Markers — the Southern Utah Reality</h2>
            <p>Flush markers hold water differently than uprights. When rain or irrigation over-spray hits an upright, it sheets off the polished face. When it hits a flush marker, it pools on the top surface — and Southern Utah water is heavy in calcium and magnesium, so it leaves mineral crusts.</p>
            <p>The practical effect: a flat marker in a St. George cemetery will typically show visible hard-water spotting within 12–24 months. This is universal here, not a defect. Two things make it manageable:</p>
