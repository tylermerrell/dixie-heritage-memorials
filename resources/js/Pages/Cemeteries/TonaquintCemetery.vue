            <h2>Maintaining a Headstone at Tonaquint</h2>
            <p>Tonaquint's environment is punishing for stone. Three factors matter more here than in most cemeteries in Utah:</p>
            <ol>
              <li><strong>Hard water.</strong> Municipal water in St. George runs high in calcium and magnesium. Irrigation over-spray and rainfall runoff both leave mineral crusts on granite — worst on light and salt-and-pepper colors, less visible on jet black and dakota mahogany. Plan for a gentle non-ionic cleaning every 18–24 months. Never use vinegar or household descalers on the polished face; they permanently etch the surface.</li>
              <li><strong>Sun.</strong> St. George averages over 300 sunny days a year. Dark polished granites hold color and contrast for decades. Softer stones and marble should be avoided.</li>
              <li><strong>Dust.</strong> Sandblast-carved letters trap red-rock dust that accumulates over years. Laser-etched imagery on polished granite is dramatically more forgiving of dust in this environment than deep-cut sandblast on rougher finishes.</li>
