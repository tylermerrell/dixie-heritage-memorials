            <h2>Marker Options at Southern Utah National Cemetery</h2>
            <p>Government-furnished markers at national cemeteries follow a uniform standard — this is what creates the recognizable orderly appearance of the grounds. Southern Utah National Cemetery offers:</p>
            <h3>Flat Markers</h3>
            <ul>
              <li><strong>Granite flat marker</strong> — 24" x 12" x 4", light gray polished granite. Standard inscription: name, branch, dates, rank, wars served.</li>
              <li><strong>Marble flat marker</strong> — same dimensions as granite. Marble weathers more quickly in the desert sun than granite; families in Southern Utah's climate typically choose granite.</li>
              <li><strong>Bronze flat marker</strong> — 24" x 12" x 3/4" mounted on a granite base. Bronze develops a patina and holds up well in high-UV conditions.</li>
            </ul>
            <h3>Upright Markers</h3>
            <ul>
              <li><strong>Granite upright</strong> — 42" x 13" x 4", light gray. Used in specific sections of the cemetery designated for uprights.</li>
              <li><strong>Marble upright</strong> — same dimensions. Same weathering caveat as marble flat.</li>
            </ul>
