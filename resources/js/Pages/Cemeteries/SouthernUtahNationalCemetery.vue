            <h2>The Application Process</h2>
            <p>Two separate applications matter:</p>
            <h3>Burial at Southern Utah National Cemetery — VA Form 40-10007</h3>
            <p>The family or funeral director submits <strong>VA Form 40-10007 (Application for Pre-Need Determination of Eligibility for Burial in a VA National Cemetery)</strong>. This can be filed at any time — while the veteran is living (recommended) or at the time of death. The VA processes it and issues an eligibility determination the family holds on file.</p>
            <p>At time of death, the funeral director calls the National Cemetery Scheduling Office. If a pre-need determination exists, scheduling is faster.</p>

            <h3>Government-Furnished Marker — VA Form 40-1330</h3>
            <p>For a marker (either at SUNC or on a private grave), the family submits <strong>VA Form 40-1330 (Claim for Standard Government Headstone or Marker)</strong>. Includes veteran information, discharge documentation, requested emblem, and any personalized inscription.</p>
            <p>Processing typically takes 8–10 weeks after submission. Setting at Southern Utah National Cemetery happens during the next scheduled installation window; setting on a private grave is coordinated with the local cemetery sexton (which we handle for Washington County families).</p>

            <h3>VA Medallion for Post-1990 Veterans — VA Form 40-1330M</h3>
            <p>If the veteran died on or after November 1, 1990, and the family wants a private headstone rather than the government marker, they can request a bronze VA medallion affixed to the private stone. Submit <strong>VA Form 40-1330M</strong>. The medallion is free; we affix it during our installation.</p>

