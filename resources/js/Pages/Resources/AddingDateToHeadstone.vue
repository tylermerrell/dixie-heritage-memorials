              <li><strong>Cemetery permit (if required).</strong> We contact your cemetery to confirm whether a permit or written approval is required before modifying an existing monument. Most Washington County municipal cemeteries require notification; some require a formal approval. We handle this step.</li>
              <li><strong>On-site engraving.</strong> Depending on the addition, we use sandblasting (for letter carving matching the original) or laser etching (for portrait medallions and detailed imagery). A straight date addition typically takes one to two hours on-site.</li>
              <li><strong>Paint fill matching.</strong> If the original letters have a white or gray paint fill, we match it. Over time, fill color oxidizes differently from the granite — on older stones, all the lettering may benefit from a fresh fill to create a uniform look.</li>
            </ol>
