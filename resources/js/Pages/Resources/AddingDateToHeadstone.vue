            <h2>How on-site engraving works</h2>
            <p>Adding an inscription to an existing headstone in a Southern Utah cemetery is typically done in the field — the monument stays in place and we bring the equipment to the cemetery. The process:</p>
            <ol>
              <li><strong>We photograph the stone.</strong> Before any work, we document the existing lettering, finish, and granite color so the new inscription matches as closely as possible in style, depth, and fill color.</li>
