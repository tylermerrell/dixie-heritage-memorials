            <h2>Maintenance schedule for Southern Utah</h2>
            <p>Given our hard water, a reasonable schedule for a grave marker in an irrigated section of a Washington County cemetery:</p>
            <ul>
              <li><strong>Every 12–18 months:</strong> full cleaning with non-ionic cleaner as described above.</li>
              <li><strong>Each visit:</strong> a quick wipe-down with a damp microfiber cloth removes dust and pollen before they build up. This is especially worthwhile in spring when red-rock dust is heaviest.</li>
              <li><strong>After dust storms:</strong> dry brush with a soft natural-bristle brush, then wet wipe. Don't dry-rub a dusty polished surface — the dust particles act as a fine abrasive.</li>
            </ul>
            <p>Flat markers need attention more frequently than uprights because water pools on the surface instead of sheeting off. If your loved one's marker is in a flush-only section with overhead irrigation, plan on a cleaning visit every fall before the irrigation season ends.</p>
