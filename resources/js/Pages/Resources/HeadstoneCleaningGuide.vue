            <h2>Step-by-step cleaning process</h2>
            <ol>
              <li><strong>Wet the stone first.</strong> Pour clean water over the entire granite face and let it soak for two to three minutes. This loosens surface dust and prevents the cleaner from being absorbed too quickly into any rough edges around the letters.</li>
              <li><strong>Apply non-ionic cleaner.</strong> Spray or pour a small amount of D/2 (or equivalent) onto the stone. Work in sections — don't let it dry on the surface before scrubbing.</li>
              <li><strong>Scrub gently with the soft brush.</strong> Work in small circular motions on the polished face. For the letters and engravings, use the smaller brush and go with the grain of the carving. Don't press hard — the cleaner does the work.</li>
              <li><strong>Rinse thoroughly.</strong> Use your clean water to rinse all cleaner residue off. Make sure no soapy film remains — dried cleaner can leave its own haze.</li>
              <li><strong>For stubborn mineral deposits:</strong> Make a paste of baking soda and water (peanut-butter consistency). Apply to the affected area, cover with plastic wrap, and leave for two to four hours. The slight alkalinity helps lift calcium without etching. Rinse well after.</li>
              <li><strong>Dry with a microfiber cloth.</strong> Buff in one direction on the polished face. Air drying in Southern Utah's sun leaves water spots — so wipe it down before you leave.</li>
            </ol>
