            <h2>Why Southern Utah headstones stain faster than elsewhere</h2>
            <p>St. George's municipal water registers among the hardest in the United States — typically 15–20 grains per gallon (hard is anything above 7). The calcium and magnesium dissolved in that water don't evaporate when the water dries. They stay on the granite surface as a white chalky film.</p>
            <p>Two things make this worse in Washington County specifically:</p>
            <ul>
              <li><strong>Cemetery irrigation over-spray.</strong> Most Southern Utah cemeteries run sprinklers in the summer months. Markers in irrigated sections get a dose of hard water two or three times a week from May through September. A flat marker in an irrigated row at Tonaquint can develop visible spotting in its first summer.</li>
              <li><strong>300+ sunny days per year.</strong> Water evaporates fast in the desert, which concentrates the mineral residue before it can sheet off. A light rain in a humid climate washes a stone; a light rain in St. George leaves a haze behind when it dries in 20 minutes.</li>
            </ul>
            <p>The good news: polished granite is non-porous. Hard water deposits sit on the surface — they don't penetrate. If you catch them in the first year or two, cleaning is straightforward. If they build for a decade, professional restoration may be needed.</p>
