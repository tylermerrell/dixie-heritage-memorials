            <h2>What not to use — ever</h2>
            <p>This list is specific to polished granite. Each of these products is sold for hard water removal. Each will damage or permanently dull granite if used on it.</p>
            <ul>
              <li><strong>Vinegar.</strong> Acidic. Etches polished granite on contact. Even diluted white vinegar will cause visible dulling after repeated use.</li>
              <li><strong>CLR, Lime-A-Way, or any calcium/lime/rust remover.</strong> Highly acidic. Designed for tile and fiberglass — will etch granite permanently.</li>
              <li><strong>Bleach.</strong> Can lighten the stone's color and degrade the polish over time, especially on darker granites.</li>
              <li><strong>Dish soap with citrus or acid additives.</strong> Regular dish soap in very small amounts is low-risk for a one-time wash. Avoid lemon-scented or "grease-cutting" formulas — they often contain acidic components.</li>
              <li><strong>Pressure washers above 500 PSI.</strong> The force can loosen laser-etched imagery on older stones and chip sandblasted letter edges. If you're using a pressure washer at all, keep it at the lowest setting and hold it at least 18 inches from the stone.</li>
              <li><strong>Wire brushes or steel wool.</strong> Will scratch the polished surface. Even a single pass leaves visible marks.</li>
            </ul>
          </div>

