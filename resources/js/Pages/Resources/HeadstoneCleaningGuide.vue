            <h2>What you need</h2>
            <ul>
              <li><strong>A non-ionic stone cleaner.</strong> The standard recommendation is D/2 Biological Solution, available online. It is pH-neutral, biodegradable, and safe for polished granite. Avoid anything labeled "degreaser," "descaler," "alkaline cleaner," or "acid cleaner."</li>
              <li><strong>Soft brushes.</strong> A natural-bristle brush (like a soft-bristle scrub brush or a shaving brush for detail work) is ideal. Never use wire, steel, or stiff nylon — they scratch polished surfaces.</li>
              <li><strong>Clean water in a bucket.</strong> Bring your own if the cemetery is in a section with irrigation — using the sprinkler water defeats the purpose.</li>
              <li><strong>Soft microfiber cloths.</strong> For drying and buffing.</li>
              <li><strong>Plastic scraper (optional).</strong> For heavy deposits on the edges of letters. Never use metal.</li>
            </ul>
          </div>

