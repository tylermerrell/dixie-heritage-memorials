            <h2>The two paths — and the honest tradeoff</h2>
            <p>Every veteran family in Southern Utah faces the same core decision. We lay it out plainly because we believe families deserve to make it with full information:</p>

            <h3>Path 1: Free VA-issued marker at a national or qualifying cemetery</h3>
            <p>The Department of Veterans Affairs provides, at no cost to the family, a government headstone or marker for any eligible veteran in any cemetery in the world. At the Southern Utah National Cemetery, this is the standard burial — the VA provides the gravesite, the marker, perpetual care of the site, a burial flag, and a Presidential Memorial Certificate, all at no cost to the family.</p>
            <p>VA marker options at national cemeteries include:</p>
            <ul>
              <li><strong>Flat granite marker</strong> — standard gray granite, flush with the ground, with the veteran's name, branch, dates, and any approved religious emblem.</li>
              <li><strong>Flat marble marker</strong> — the traditional white marble marker. (We generally caution against marble for private cemetery installations in Southern Utah's climate, but at SUNC the VA manages the markers and the climate conditions at Cedar City's elevation differ somewhat from St. George's desert floor.)</li>
              <li><strong>Flat bronze marker</strong> — a cast bronze face mounted on a granite base. Develops a warm patina over time.</li>
              <li><strong>Upright granite or marble</strong> — available for some sections.</li>
            </ul>
            <p>There is no design flexibility on a VA-issued marker. The approved elements are standardized — name, rank, branch, dates, and a choice from a list of approved religious emblems. You cannot add a temple silhouette, a family photograph, a scripture, or custom lettering to a government-issued marker.</p>

            <h3>Path 2: Private headstone with a VA medallion at any cemetery</h3>
            <p>Veterans interred in a private or municipal cemetery — Tonaquint, St. George City Cemetery, Hurricane, Ivins, or any other non-national cemetery — can have a custom private headstone with a bronze VA medallion affixed. The medallion is issued free by the VA under VA Form 40-1330M. It identifies the deceased as a veteran and is available in three sizes.</p>
            <p>With a private headstone and VA medallion, families have full design flexibility: granite color, size and shape, temple silhouette, laser-etched portrait, companion monument, scripture, and any other approved personalization. The cost is the cost of the private headstone — the VA medallion is free.</p>
            <p>This path makes the most sense when:</p>
