              <li>The family wants the veteran buried in a local community cemetery near home — Tonaquint, Hurricane, Santa Clara — rather than the national cemetery in Cedar City.</li>
              <li>The family wants a personalized design: temple engraving, portrait, companion stone, or scripture that a government marker cannot accommodate.</li>
              <li>Other family members are buried in the same municipal cemetery and the veteran should rest with them.</li>
            </ul>
